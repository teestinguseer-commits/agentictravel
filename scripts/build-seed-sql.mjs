// Builds supabase/seed.sql from graph/experiences/*.yaml: experiences, their windows and
// knowledge pairings. Seeded facts carry confidence 'low' (or the YAML's own) so the
// Verifier re-checks them before anything is shown. Run after editing the YAML files.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { parse } from "yaml";

const DIR = "graph/experiences";
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const arr = (xs, type) => `array[${xs.map(q).join(", ")}]::${type}[]`;
const nums = (xs) => `array[${xs.join(", ")}]::smallint[]`;

const rows = { experiences: [], windows: [], pairings: new Map() };

for (const file of readdirSync(DIR).filter((f) => f.endsWith(".yaml")).sort()) {
  const raw = readFileSync(`${DIR}/${file}`, "utf8");
  const d = parse(raw);
  const sha = createHash("sha256").update(raw).digest("hex");
  const p = d.provenance;
  rows.experiences.push(
    `(${q(d.id)}, ${q(d.name)}, ${q(d.lane)}, ${q(d.hook)}, ${q(d.place.label)}, ${arr(d.place.countries, "char(2)")}, ` +
      `${nums(d.season_months)}, ${q(d.window_note)}, ${q(d.scarcity.type)}, ${q(d.scarcity.note)}, ${q(d.lead_time_note)}, ` +
      `${d.budget_band}, ${arr(d.segments, "traveller_segment")}, ${arr(d.safety_flags, "text")}, ${q(d.twin_of)}, ` +
      `${q(d.status)}, ${q(sha)})`,
  );
  const prov = `${q(p.source_url)}, ${q(p.checked_at)}, ${q(p.verified_by)}, ${q(p.confidence)}`;
  if (d.season_months.length)
    rows.windows.push(`(${q(`win_${d.id}_season`)}, ${q(d.id)}, ${nums(d.season_months)}, null, null, ${q(d.window_note)}, ${prov}, 'seasonal')`);
  for (const f of d.fixed_dates ?? [])
    rows.windows.push(
      `(${q(`win_${d.id}_${f.start}`)}, ${q(d.id)}, ${nums([Number(f.start.slice(5, 7))])}, ${q(f.start)}, ${q(f.end ?? null)}, ${q(d.window_note)}, ${prov}, 'fixed')`,
    );
  for (const pr of d.pairings ?? []) {
    const [a, b] = [d.id, pr.with].sort();
    if (!rows.pairings.has(`${a}|${b}`)) rows.pairings.set(`${a}|${b}`, `(${q(a)}, ${q(b)}, ${q(pr.reason)}, 'knowledge')`);
  }
}

const sql = `-- Generated by scripts/build-seed-sql.mjs from graph/experiences/*.yaml. Do not edit by hand.
begin;

insert into experiences (id, name, lane, hook, place_label, countries, season_months, window_note,
  scarcity, scarcity_note, lead_time_note, budget_band, segments, safety_flags, twin_of, status, definition_sha256)
values
${rows.experiences.join(",\n")}
on conflict (id) do update set
  name = excluded.name, lane = excluded.lane, hook = excluded.hook, place_label = excluded.place_label,
  countries = excluded.countries, season_months = excluded.season_months, window_note = excluded.window_note,
  scarcity = excluded.scarcity, scarcity_note = excluded.scarcity_note, lead_time_note = excluded.lead_time_note,
  budget_band = excluded.budget_band, segments = excluded.segments, safety_flags = excluded.safety_flags,
  twin_of = excluded.twin_of, status = excluded.status, definition_sha256 = excluded.definition_sha256,
  loaded_at = now();

insert into windows (id, experience_id, months, starts_on, ends_on, note, source_url, checked_at, verified_by, confidence, freshness)
values
${rows.windows.join(",\n")}
on conflict (id) do nothing;
${
  rows.pairings.size
    ? `
insert into pairings (a, b, reason, origin)
values
${[...rows.pairings.values()].join(",\n")}
on conflict (a, b) do update set reason = excluded.reason;
`
    : ""
}
commit;
`;
writeFileSync("supabase/seed.sql", sql);
console.log(`Wrote supabase/seed.sql: ${rows.experiences.length} experiences, ${rows.windows.length} windows, ${rows.pairings.size} pairings`);
